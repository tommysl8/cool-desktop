// Build plugin: dist/wallpaper, the Lively web wallpaper.
//
//   dist/wallpaper/                  the package folder = the zip root
//     index.html                     src/wallpaper/index.html with the stylesheet links and the deferred scripts
//     LivelyInfo.json                src/wallpaper/LivelyInfo.json, checked against LIVELY_INFO below (strict JSON,
//                                    "Arguments": "--pause-event true" and no other flag)
//     LivelyProperties.json          generated: PCD.wpProps.buildProperties(config, { menu }) over the synced engine's
//                                    theme menu (PCD.engine.menu), so the Customise panel cannot drift from the page
//     thumbnail.jpg                  the built page in headless Chrome (sample city Berlin, mocked weather); with
//                                    --no-render (or when the render fails) src/wallpaper/thumbnail.jpg
//     js/lively.js                   the Lively callbacks: blocking, first in <head>
//     js/pixelclock/                 the synced engine, flat page layout, bytes unchanged (ctx.copyVendor)
//     js/pcd-*.js, css/*, fonts/     ctx.copyShared: the hook, the generated tokens/anchors, src/shared/*.js and css
//     js/pcd-config.js               generated: PCD.settings.configJs(config) (PCD.CONFIG, the page defaults; only the
//                                    fields the wallpaper's settings read, plus taskbarPx)
//     js/ntp-settings.js             the one settings schema (copied from src/newtab/js); the wallpaper sees it through
//                                    PCD.wpProps.schemaFor (plus its own "side")
//     js/wp-*.js, css/wallpaper.css  the app (the column and the scene layer are the shared js/pcd-console.js and
//                                    js/pcd-bleed.js)
//   dist/PixelClockDesktop-wallpaper.zip is written by tools/build.mjs right after this plugin (tools/lib/zip.py: posix
//   names, files at the root, ZIP_DEFLATED; never Compress-Archive).
//
// Privacy: the thumbnail render runs in tools/lib/chrome.mjs launch() with the privacy guard and weather 'mock', and
// the page starts with the sample city (?city=Berlin): the configured city is never looked up.
// Node built-ins only.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { loadEngine } from '../lib/anchors.mjs';
import { findBrowser, launch } from '../lib/chrome.mjs';
import { sleep } from '../lib/fsx.mjs';
import { imageSize } from '../lib/png.mjs';
import { serve } from '../lib/serve.mjs';
import { vendorDir } from '../lib/vendor.mjs';

export const piece = 'wallpaper';
export const OUT = 'wallpaper';
export const ZIP = 'PixelClockDesktop-wallpaper.zip';
/** The four files Lively needs at the zip root. */
export const ROOT_FILES = ['index.html', 'LivelyInfo.json', 'LivelyProperties.json', 'thumbnail.jpg'];
export const STYLE_MARK = '<!-- PCD:STYLES -->';
export const SCRIPT_MARK = '<!-- PCD:SCRIPTS -->';
/** The blocking first script: Lively calls its functions in the page's global scope, even before the page is ready. */
export const LIVELY_SCRIPT = 'js/lively.js';
/** Generated by this plugin into js/. */
export const CONFIG_SCRIPT = 'pcd-config.js';
/** The settings schema shared with the new tab. */
export const SETTINGS_SRC = ['src', 'newtab', 'js', 'ntp-settings.js'];
export const SETTINGS_SCRIPT = 'ntp-settings.js';
/** The wallpaper's own scripts after the shared ones, in load order. */
export const APP_SCRIPTS = Object.freeze(['wp-props.js', 'wp-loop.js', 'wp-app.js']);
export const APP_STYLES = Object.freeze(['wallpaper.css']);
/** LivelyInfo.json: a shape Lively is known to accept. Type 1 = web; never a flag Lively passes itself. */
export const LIVELY_INFO = Object.freeze({
  AppVersion: '2.2.1.0',
  Title: 'PixelClock Desktop',
  Thumbnail: 'thumbnail.jpg',
  Preview: null,
  Desc: "The PixelClock's pixel-art scenes as a live desktop: themes by date, real time of day, weather",
  Author: '',
  License: '',
  Contact: '',
  Type: 1,
  FileName: 'index.html',
  Arguments: '--pause-event true',
  IsAbsolutePath: false,
  Id: null,
  Tags: null,
  Version: 0,
});
/** The bytes of LivelyInfo.json: one line, no spaces, a final LF. */
export const LIVELY_INFO_TEXT = JSON.stringify(LIVELY_INFO) + '\n';
/**
 * Thumbnail render: the page at 1280x800 CSS px, DPR 1, JPEG under 300 KB, the sample city in its own time zone (so
 * the mocked Berlin sunrise and sunset label the daylight strip) at a fixed evening hour of the build day (the same
 * picture whenever the build runs that day: the scene the date picks, at night), mocked weather.
 */
export const THUMB = Object.freeze({
  width: 1280, height: 800, dpr: 1, maxBytes: 300 * 1024, settleMs: 1600, timeoutMs: 30000,
  query: '?city=Berlin', timezone: 'Europe/Berlin', at: Object.freeze([20, 40]), qualities: Object.freeze([85, 75, 65, 55, 45]),
});

/** A page script that runs the page clock from today at h:m (local to the page's time zone): Date shifts, timers do not. */
export function clockScript(h, m) {
  return `(() => {
  const Real = Date;
  const t = new Real(Real.now());
  t.setHours(${Number(h)}, ${Number(m)}, 0, 0);
  const offset = t.getTime() - Real.now();
  class ShiftedDate extends Real {
    constructor(...a) { if (a.length) super(...a); else super(Real.now() + offset); }
    static now() { return Real.now() + offset; }
  }
  window.Date = ShiftedDate;
})();`;
}

/** Deferred script src values in page order, from a build ctx (anything with pageScripts). */
export function deferredScripts(ctx) {
  return [
    ...ctx.pageScripts({ js: 'js', vendor: 'js/pixelclock' }),
    `js/${CONFIG_SCRIPT}`,
    `js/${SETTINGS_SCRIPT}`,
    ...APP_SCRIPTS.map((n) => `js/${n}`),
  ];
}

/** Stylesheet href values in page order: the generated tokens.css, the shared styles, wallpaper.css. */
export function pageStyles(ctx) {
  const generated = ctx.generated && ctx.generated['tokens.css'] !== undefined ? ['tokens.css'] : [];
  return [...generated, ...ctx.sharedStyles, ...APP_STYLES].map((n) => `css/${n}`);
}

/** index.html from the template: stylesheet links at STYLE_MARK, deferred classic scripts at SCRIPT_MARK. */
export function renderHtml(template, { scripts, styles }) {
  for (const mark of [STYLE_MARK, SCRIPT_MARK]) {
    const n = template.split(mark).length - 1;
    if (n !== 1) throw new Error(`src/wallpaper/index.html must contain ${mark} exactly once (found ${n})`);
  }
  const css = styles.map((h) => `<link rel="stylesheet" href="${h}">`).join('\n');
  const js = scripts.map((s) => `<script src="${s}" defer></script>`).join('\n');
  return template.replace(STYLE_MARK, () => css).replace(SCRIPT_MARK, () => js);
}

/** Run classic UMD files as functions of a private `globalThis` object (nothing global is read or written). */
export function loadPrivate(files, scope = {}) {
  for (const file of files) {
    vm.compileFunction(fs.readFileSync(file, 'utf8'), ['globalThis'], { filename: file })(scope);
  }
  return scope;
}

/**
 * The settings schema, the property mapper and the theme menu, loaded privately from the repo:
 * { S: the wallpaper's schema (PCD.wpProps.schemaFor(PCD.settings)), P: PCD.wpProps, menu: PCD.engine.menu(PC) as
 * [{ id, name }], PC }.
 */
export function loadModel(root) {
  const PC = loadEngine(vendorDir(root));
  const scope = loadPrivate([
    path.join(root, 'src', 'shared', 'pcd-engine.js'),
    path.join(root, ...SETTINGS_SRC),
    path.join(root, 'src', 'wallpaper', 'js', 'wp-props.js'),
  ], { PixelClock: PC });
  const PCD = scope.PCD;
  if (!PCD || !PCD.engine || !PCD.settings || !PCD.wpProps) throw new Error('wallpaper: pcd-engine.js, ntp-settings.js or wp-props.js did not load');
  const menu = PCD.engine.menu(PC).map((t) => ({ id: t.id, name: t.name }));
  return { S: PCD.wpProps.schemaFor(PCD.settings), P: PCD.wpProps, menu, PC };
}

/**
 * Only the config fields the wallpaper's settings read (and taskbarPx, the band the column keeps clear) go into
 * the package; the new tab's shortcuts and every other field stay out.
 */
export function wallpaperConfig(config, S) {
  const c = config && typeof config === 'object' ? config : {};
  const fields = new Set(['taskbarPx']);
  for (const d of S.KEYS) if (d.scopes.includes('wallpaper')) for (const f of d.config) fields.add(f);
  const out = {};
  for (const k of Object.keys(c)) if (fields.has(k)) out[k] = c[k];
  return out;
}

/** LivelyProperties.json for a config (the object; the build writes it with 2-space indent and a final LF). */
export function genProperties(root, config, model = loadModel(root)) {
  return model.P.buildProperties(wallpaperConfig(config, model.S), { menu: model.menu, schema: model.S });
}

/** js/pcd-config.js for a config (wallpaper fields only). */
export function genConfigJs(root, config, model = loadModel(root)) {
  return model.S.configJs(wallpaperConfig(config, model.S));
}

/** src/wallpaper/LivelyInfo.json, required to be exactly LIVELY_INFO_TEXT (strict JSON, one line, final LF). */
export function readLivelyInfo(root) {
  const file = path.join(root, 'src', 'wallpaper', 'LivelyInfo.json');
  const buf = fs.readFileSync(file);
  if (buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf) throw new Error('src/wallpaper/LivelyInfo.json starts with a BOM');
  const text = buf.toString('utf8');
  const info = JSON.parse(text);
  if (JSON.stringify(info) !== JSON.stringify(LIVELY_INFO)) {
    throw new Error(`src/wallpaper/LivelyInfo.json differs from LIVELY_INFO:\n  got  ${JSON.stringify(info)}\n  want ${JSON.stringify(LIVELY_INFO)}`);
  }
  if (text.replace(/\r\n/g, '\n') !== LIVELY_INFO_TEXT) throw new Error('src/wallpaper/LivelyInfo.json must be one line of JSON without spaces plus a final LF');
  return info;
}

/**
 * thumbnail.jpg: the built page in headless Chrome (launch(): privacy guard on, Open-Meteo mocked), started with the
 * sample city in its time zone at THUMB.at, captured once the first frame is up, the weather is in, the dimming and the
 * bands have settled and the clock's colon is lit. Resolves the JPEG bytes; throws on a page error, a blocked request
 * or a JPEG over THUMB.maxBytes at every quality.
 */
export async function renderThumbnail(dir, { log = () => {} } = {}) {
  const site = await serve(dir);
  let browser = null;
  let buf = null;
  try {
    browser = await launch({ windowSize: [THUMB.width, THUMB.height], weather: 'mock' });
    const page = await browser.newPage('about:blank');
    await page.send('Emulation.setTimezoneOverride', { timezoneId: THUMB.timezone });
    await page.send('Page.addScriptToEvaluateOnNewDocument', { source: clockScript(...THUMB.at) });
    await page.setViewport(THUMB.width, THUMB.height, THUMB.dpr);
    await page.goto(site.url + 'index.html' + THUMB.query);
    await page.waitFor("document.documentElement.getAttribute('data-ready') === '1'", { timeoutMs: THUMB.timeoutMs });
    await page.waitFor("(() => { const w = window.__pcd && window.__pcd.weather(); return !!w && !!w.status; })()", { timeoutMs: THUMB.timeoutMs });
    await sleep(THUMB.settleMs);
    await page.waitFor("(() => { const c = document.querySelector('.pcd-colon'); return !c || getComputedStyle(c).visibility !== 'hidden'; })()", { timeoutMs: 3000 });
    // the way Lively pauses it: no timer and no frame from here on, so the colon stays lit and the frame stays put
    await page.evaluate(`livelyWallpaperPlaybackChanged('{"IsPaused":true}')`);
    const s = await page.evaluate('window.__pcd.snapshot()');
    const problems = [];
    if (s.stats.errorCount) problems.push(`page errors: ${s.stats.errors.join('; ')}`);
    for (const e of page.errors) problems.push(`${e.type}: ${e.text}`);
    if (problems.length) throw new Error(`thumbnail render: ${problems.join('\n')}`);
    for (const quality of THUMB.qualities) {
      const shot = await page.screenshot({ format: 'jpeg', quality });
      const size = imageSize(shot);
      if (size.type !== 'jpeg') throw new Error(`thumbnail render wrote ${size.type}, expected jpeg`);
      log(`thumbnail ${size.width}x${size.height} jpeg at quality ${quality}: ${shot.length} bytes`);
      if (shot.length <= THUMB.maxBytes) { buf = shot; break; }
    }
    if (!buf) throw new Error(`thumbnail stays over ${THUMB.maxBytes} bytes even at JPEG quality ${THUMB.qualities[THUMB.qualities.length - 1]}`);
    const reqs = browser.weatherRequests;
    if (!reqs.every((r) => r.action === 'mocked')) throw new Error('thumbnail render: an Open-Meteo request was not mocked');
    log(`thumbnail: theme ${s.scene.id} (${s.scene.tag}), column ${s.state.side}, k ${s.metrics && s.metrics.k}, weather ${s.weather ? s.weather.status : 'none'}; ${reqs.length} Open-Meteo request(s), all mocked; ${browser.violations.length} blocked`);
  } finally {
    if (browser) await browser.close();
    await site.close();
  }
  browser.assertNoViolations();
  return buf;
}

export async function build(ctx) {
  const thumbRel = `${OUT}/thumbnail.jpg`;
  let oldThumb = null;
  try { oldThumb = fs.readFileSync(ctx.out(thumbRel)); } catch { /* none yet */ }

  const info = readLivelyInfo(ctx.root);
  const model = loadModel(ctx.root);
  ctx.clean(OUT);

  const src = (...p) => ctx.path('src', 'wallpaper', ...p);
  ctx.copyVendor(`${OUT}/js/pixelclock`);
  ctx.copyShared(OUT);
  ctx.write(`${OUT}/js/${CONFIG_SCRIPT}`, genConfigJs(ctx.root, ctx.config, model));
  ctx.write(`${OUT}/js/${SETTINGS_SCRIPT}`, fs.readFileSync(ctx.path(...SETTINGS_SRC), 'utf8'));
  ctx.write(`${OUT}/${LIVELY_SCRIPT}`, fs.readFileSync(src('js', 'lively.js'), 'utf8'));
  for (const name of APP_SCRIPTS) ctx.write(`${OUT}/js/${name}`, fs.readFileSync(src('js', name), 'utf8'));
  for (const name of APP_STYLES) ctx.write(`${OUT}/css/${name}`, fs.readFileSync(src('css', name), 'utf8'));

  const template = fs.readFileSync(src('index.html'), 'utf8');
  ctx.write(`${OUT}/index.html`, renderHtml(template, { scripts: deferredScripts(ctx), styles: pageStyles(ctx) }));
  if (JSON.stringify(info) + '\n' !== LIVELY_INFO_TEXT) throw new Error('LivelyInfo.json changed while building');
  ctx.write(`${OUT}/LivelyInfo.json`, LIVELY_INFO_TEXT);
  ctx.writeJson(`${OUT}/LivelyProperties.json`, genProperties(ctx.root, ctx.config, model));

  // thumbnail.jpg: rendered, else the committed fallback, else the previous build's
  const fallback = src('thumbnail.jpg');
  let thumb = null;
  if (ctx.render && findBrowser()) {
    try {
      thumb = await renderThumbnail(ctx.out(OUT), { log: ctx.log });
    } catch (e) {
      ctx.log(`WARNING: thumbnail render failed (${String(e && e.message ? e.message : e).split('\n')[0]}); using the fallback`);
    }
  } else if (ctx.render) {
    ctx.log('WARNING: no Chrome or Edge to render thumbnail.jpg; using the fallback');
  }
  if (thumb) ctx.writeBytes(thumbRel, thumb);
  else if (fs.existsSync(fallback)) {
    ctx.copyFile(fallback, thumbRel);
    ctx.log('thumbnail.jpg from src/wallpaper/thumbnail.jpg');
  } else if (oldThumb) {
    ctx.writeBytes(thumbRel, oldThumb);
    ctx.log('thumbnail.jpg kept from the previous build');
  } else {
    ctx.log('WARNING: no thumbnail.jpg (no render and no src/wallpaper/thumbnail.jpg); the validator will fail');
  }
}
