#!/usr/bin/env node
// PixelClock Desktop build: node tools/build.mjs [piece ...] [--no-sync] [--no-render]
//
// 1. Sync (unless --no-sync): when a PixelClock checkout sits next to this folder (or PCD_PIXELCLOCK names one),
//    tools/sync.mjs first copies the clock's engine byte for byte into vendor/pixelclock/ (read-only on the clock
//    repo). A failed sync stops the build and vendor/ keeps its last good copy. With no checkout there, or with
//    --no-sync, the build uses vendor/pixelclock/ as it is.
// 2. Inputs, checked before any piece runs: config/user.json (strict JSON, tools/lib/config.mjs) and
//    vendor/pixelclock/ against its SYNC.json.
// 3. Generate stage:
//    - tools/lib/tokens.mjs: `export function generate({ root, config })` returning
//      { files: { 'pcd-tokens.js': text, 'tokens.css': text }, rows?: contrast rows } and throwing when the
//      contrast gate fails (that stops the build).
//    - tools/lib/anchors.mjs: `export function generate(vendorDir)` returning the anchors object; the build writes it
//      as anchors.json and as pcd-anchors.js (PCD.ANCHORS) for copyShared().
// 4. Pieces: tools/build/<piece>.mjs in the order style-tile, newtab, wallpaper, still (or only the named ones). A
//    plugin exports `export const piece = '<piece>'` and `export async function build(ctx)`; a piece without a
//    plugin file is skipped. Each plugin cleans only dist/<piece>.
// 5. Zip: when the wallpaper piece built, dist/wallpaper/ -> dist/PixelClockDesktop-wallpaper.zip (tools/lib/zip.py,
//    posix names; never Compress-Archive).
// Every text write is UTF-8 without BOM with LF line endings. Node built-ins only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as fsx from './lib/fsx.mjs';
import { loadConfig } from './lib/config.mjs';
import { assertVendor, themeOrder, vendorDir, vendorTarget } from './lib/vendor.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '..');

/** Pieces in build order. */
export const PIECES = ['style-tile', 'newtab', 'wallpaper', 'still'];
/** Loaded right after the vendor engine.js, before schedule.js and the themes. */
export const HOOK_SCRIPT = 'pcd-hook.js';
/** Generated by the build (never hand-written in src/shared/). */
export const GENERATED_SCRIPTS = ['pcd-tokens.js', 'pcd-anchors.js'];
export const GENERATED_STYLES = ['tokens.css'];
/** src/shared/ script order after the vendor scripts and the generated ones. */
export const SHARED_SCRIPTS = ['pcd-core.js', 'pcd-font.js', 'pcd-engine.js', 'pcd-sun.js', 'pcd-weather.js', 'pcd-fx.js', 'pcd-greet.js', 'pcd-ascii.js', 'pcd-layout.js', 'pcd-host.js', 'pcd-bleed.js', 'pcd-console.js'];
/** src/shared/css/ style order (tokens.css is generated). */
export const SHARED_STYLES = ['tokens.css', 'pcd-base.css', 'pcd-console.css'];
/** design/fonts/ files copied by copyShared. */
export const FONT_FILES = ['CascadiaMono-wght.ttf', 'OFL.txt'];
/** The font's licence: copyShared never ships a font file without it. */
export const FONT_LICENCE = 'OFL.txt';
export const ZIP_NAME = 'PixelClockDesktop-wallpaper.zip';

const USAGE = `usage: node tools/build.mjs [piece ...] [--no-sync] [--no-render]
pieces (build order): ${PIECES.join(', ')}
  --no-sync     skip the engine refresh and build from vendor/pixelclock/ as it is
  --no-render   skip steps that need headless Chrome (thumbnails, rendered icons)
The engine refresh copies the clock's engine from ../PixelClock (or the folder in PCD_PIXELCLOCK) into
vendor/pixelclock/ first; with no checkout there, the build skips it.`;

/** { pieces, sync, render, help, errors } from command-line arguments. */
export function parseArgs(argv) {
  const res = { pieces: [], sync: true, render: true, help: false, errors: [] };
  for (const a of argv) {
    if (a === '--no-render') res.render = false;
    else if (a === '--no-sync') res.sync = false;
    else if (a === '-h' || a === '--help') res.help = true;
    else if (a.startsWith('-')) res.errors.push(`unknown option ${a}`);
    else if (!PIECES.includes(a)) res.errors.push(`unknown piece "${a}" (known: ${PIECES.join(', ')})`);
    else if (!res.pieces.includes(a)) res.pieces.push(a);
  }
  return res;
}

/**
 * Ordered shared file lists from src/shared/ (scripts) and src/shared/css/ (styles): documented files that exist,
 * then any other .js/.css sorted by name. Generated names found there are conflicts.
 */
export function sharedLists(root) {
  const jsDir = path.join(root, 'src', 'shared');
  const cssDir = path.join(jsDir, 'css');
  const names = (dir, ext) => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isFile() && path.extname(e.name).toLowerCase() === ext).map((e) => e.name) : []);
  const js = names(jsDir, '.js');
  const css = names(cssDir, '.css');
  const scripts = [
    ...SHARED_SCRIPTS.filter((n) => js.includes(n)),
    ...js.filter((n) => n !== HOOK_SCRIPT && !SHARED_SCRIPTS.includes(n) && !GENERATED_SCRIPTS.includes(n)).sort(),
  ];
  const styles = [
    ...SHARED_STYLES.filter((n) => !GENERATED_STYLES.includes(n) && css.includes(n)),
    ...css.filter((n) => !SHARED_STYLES.includes(n)).sort(),
  ];
  const conflicts = [...js.filter((n) => GENERATED_SCRIPTS.includes(n)), ...css.filter((n) => GENERATED_STYLES.includes(n))];
  return { jsDir, cssDir, hook: js.includes(HOOK_SCRIPT), scripts, styles, conflicts };
}

/** The pcd-anchors.js text for an anchors object (UMD, sets PCD.ANCHORS). */
export function anchorsJs(anchors) {
  return [
    '/* PixelClock Desktop: generated by tools/build.mjs from tools/lib/anchors.mjs. Do not edit. */',
    '(function (root, factory) {',
    '  var api = factory(root.PCD || (root.PCD = {}));',
    "  if (typeof module === 'object' && module.exports) module.exports = api;",
    "})(typeof globalThis !== 'undefined' ? globalThis : this, function (PCD) {",
    "  'use strict';",
    `  PCD.ANCHORS = ${JSON.stringify(anchors)};`,
    '  return PCD.ANCHORS;',
    '});',
    '',
  ].join('\n');
}

/**
 * The generate stage: tools/lib/tokens.mjs and tools/lib/anchors.mjs (see the header).
 * Resolves { generated: { name: text }, tokens, anchors, rows, notes }; throws when a module fails.
 */
export async function generateStage({ root, config, vendor }) {
  const generated = {};
  const notes = [];
  let tokens = null;
  let anchors = null;
  let rows = [];
  const tokensMod = path.join(root, 'tools', 'lib', 'tokens.mjs');
  if (fs.existsSync(tokensMod)) {
    const mod = await import(pathToFileURL(tokensMod).href);
    if (typeof mod.generate !== 'function') throw new Error('tools/lib/tokens.mjs does not export generate({ root, config })');
    const r = await mod.generate({ root, config });
    const files = r && r.files ? r.files : r;
    for (const [name, text] of Object.entries(files || {})) {
      if (![...GENERATED_SCRIPTS, ...GENERATED_STYLES].includes(name) || typeof text !== 'string') throw new Error(`tools/lib/tokens.mjs generated an unexpected file ${name}`);
      generated[name] = text;
    }
    tokens = (r && r.tokens) || null;
    rows = (r && Array.isArray(r.rows) ? r.rows : []);
    notes.push(`tokens: ${Object.keys(files || {}).join(', ') || 'nothing'}${rows.length ? `; contrast gate PASS (${rows.length} pairs)` : ''}`);
  } else {
    notes.push('tokens: no tools/lib/tokens.mjs (no pcd-tokens.js / tokens.css)');
  }
  const anchorsMod = path.join(root, 'tools', 'lib', 'anchors.mjs');
  if (fs.existsSync(anchorsMod)) {
    const mod = await import(pathToFileURL(anchorsMod).href);
    if (typeof mod.generate !== 'function') throw new Error('tools/lib/anchors.mjs does not export generate(vendorDir)');
    anchors = await mod.generate(vendor);
    generated['pcd-anchors.js'] = anchorsJs(anchors);
    generated['anchors.json'] = JSON.stringify(anchors, null, 2) + '\n';
    notes.push(`anchors: ${Object.keys(anchors || {}).length} entries`);
  } else {
    notes.push('anchors: no tools/lib/anchors.mjs (no pcd-anchors.js / anchors.json)');
  }
  return { generated, tokens, anchors, rows, notes };
}

/**
 * The ctx handed to build plugins.
 * opts: { root, dist?, config, tokens?, anchors?, generated?, render, piece?, log?, shared? }
 * Members: root dist piece config tokens anchors render generated sharedScripts sharedStyles stats log
 *          path out clean write writeJson writeBytes copyFile copyDir copyShared copyVendor pageScripts
 */
export function createContext(opts) {
  const root = path.resolve(opts.root);
  const dist = path.resolve(opts.dist || path.join(root, 'dist'));
  const piece = opts.piece || null;
  const print = opts.log || console.log;
  const shared = opts.shared || sharedLists(root);
  const generated = opts.generated || {};
  const stats = { files: 0, bytes: 0 };
  let order = null;

  const log = (msg) => print(`[${piece || 'build'}] ${msg}`);
  const distRel = (abs) => {
    const rel = fsx.toPosix(path.relative(dist, abs));
    return rel ? `dist/${rel}` : 'dist';
  };
  const rootRel = (abs) => (fsx.isInside(root, abs) ? fsx.toPosix(path.relative(root, abs)) || '.' : abs);
  const checkParts = (fn, parts) => {
    for (const p of parts) {
      if (typeof p !== 'string') throw new TypeError(`ctx.${fn}: path parts must be strings (got ${typeof p})`);
      if (path.isAbsolute(p) || /^[a-zA-Z]:/.test(p)) throw new Error(`ctx.${fn}: absolute path not allowed: ${p}`);
      if (p.includes('\0')) throw new Error(`ctx.${fn}: NUL in path`);
    }
  };
  const count = (n) => { stats.files += 1; stats.bytes += n; };
  const posixJoin = (...parts) => parts.filter((p) => p !== '' && p !== '.').join('/');

  function out(...rel) {
    checkParts('out', rel);
    const p = path.resolve(dist, ...rel);
    if (!fsx.isInside(dist, p)) throw new Error(`ctx.out: "${rel.join('/')}" escapes dist/`);
    return p;
  }

  function file(fn, rel) {
    const p = out(rel);
    if (path.relative(dist, p) === '') throw new Error(`ctx.${fn}: "${rel}" is dist/ itself, not a file`);
    return p;
  }

  const vendorPath = vendorDir(root);
  const vendorOrder = () => (order ??= themeOrder(vendorPath));

  const ctx = {
    root,
    dist,
    piece,
    config: opts.config,
    tokens: opts.tokens || null,
    anchors: opts.anchors || null,
    render: opts.render !== false,
    generated,
    sharedScripts: [...shared.scripts],
    sharedStyles: [...shared.styles],
    stats,
    log,

    /** Absolute path under the repo root (throws if it escapes the root). */
    path(...rel) {
      checkParts('path', rel);
      const p = path.resolve(root, ...rel);
      if (!fsx.isInside(root, p)) throw new Error(`ctx.path: "${rel.join('/')}" escapes the repo root`);
      return p;
    },

    out,

    /** Delete and recreate dist/<rel>. Refuses an empty rel, dist itself and anything outside dist. */
    clean(rel) {
      if (typeof rel !== 'string' || rel.trim() === '') throw new Error('ctx.clean: refusing an empty path (it would delete all of dist/)');
      const p = out(rel);
      if (path.relative(dist, p) === '') throw new Error(`ctx.clean: refusing "${rel}": it is dist/ itself`);
      fs.rmSync(p, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
      fs.mkdirSync(p, { recursive: true });
      log(`clean ${distRel(p)}`);
      return p;
    },

    /** UTF-8 without BOM, CRLF -> LF, mkdir -p. */
    write(rel, text) {
      if (typeof text !== 'string') throw new TypeError(`ctx.write(${rel}): text must be a string`);
      const p = file('write', rel);
      const n = fsx.writeText(p, text);
      count(n);
      log(`write ${distRel(p)} (${n} bytes)`);
      return p;
    },

    writeJson(rel, obj) {
      return ctx.write(rel, JSON.stringify(obj, null, 2) + '\n');
    },

    writeBytes(rel, buf) {
      const p = file('writeBytes', rel);
      const n = fsx.writeBytes(p, buf);
      count(n);
      log(`write ${distRel(p)} (${n} bytes)`);
      return p;
    },

    /** Copy one file into dist (bytes unchanged). absSrc may also be relative to the repo root. */
    copyFile(absSrc, rel) {
      const src = path.resolve(root, absSrc);
      const p = file('copyFile', rel);
      const n = fsx.copyFile(src, p);
      count(n);
      log(`copy ${rootRel(src)} -> ${distRel(p)} (${n} bytes)`);
      return p;
    },

    /** Copy a folder into dist. filter(rel, abs, isDir) may return false to skip an entry. */
    copyDir(absSrc, rel, { filter } = {}) {
      const src = path.resolve(root, absSrc);
      const p = out(rel);
      const copied = fsx.copyDir(src, p, { filter });
      let bytes = 0;
      for (const c of copied) { count(c.bytes); bytes += c.bytes; }
      log(`copy ${rootRel(src)}/ -> ${distRel(p)}/ (${copied.length} files, ${bytes} bytes)`);
      return copied.map((c) => c.rel);
    },

    /**
     * Shared files into dist/<rel>: pcd-hook.js, the generated pcd-tokens.js / pcd-anchors.js and src/shared/*.js
     * into <js>/, the generated tokens.css and src/shared/css/*.css into <css>/, design/fonts/ (font + OFL.txt)
     * into <fonts>/. Pass false for js, css or fonts to leave that group out. Returns the written paths relative to
     * dist/<rel> as { js, css, fonts }. Throws before writing anything when a font file is there without its licence.
     */
    copyShared(rel, { js = 'js', css = 'css', fonts = 'fonts' } = {}) {
      if (typeof rel !== 'string' || rel.trim() === '') throw new Error('ctx.copyShared: rel (the piece folder under dist/) is required');
      if (shared.conflicts.length) throw new Error(`src/shared/ must not contain ${shared.conflicts.join(', ')} (generated by the build)`);
      const present = fonts ? FONT_FILES.filter((name) => fs.existsSync(path.join(root, 'design', 'fonts', name))) : [];
      if (present.some((name) => name !== FONT_LICENCE) && !present.includes(FONT_LICENCE)) {
        throw new Error(`design/fonts/${FONT_LICENCE} is missing: the font must travel with its licence`);
      }
      const written = { js: [], css: [], fonts: [] };
      const text = (dir, name) => fs.readFileSync(path.join(dir, name), 'utf8');
      if (js) {
        const list = [
          ...(shared.hook ? [{ name: HOOK_SCRIPT, body: () => text(shared.jsDir, HOOK_SCRIPT) }] : []),
          ...GENERATED_SCRIPTS.filter((n) => generated[n] !== undefined).map((n) => ({ name: n, body: () => generated[n] })),
          ...shared.scripts.map((n) => ({ name: n, body: () => text(shared.jsDir, n) })),
        ];
        for (const s of list) {
          ctx.write(path.join(rel, js, s.name), s.body());
          written.js.push(posixJoin(js, s.name));
        }
      }
      if (css) {
        const list = [
          ...GENERATED_STYLES.filter((n) => generated[n] !== undefined).map((n) => ({ name: n, body: () => generated[n] })),
          ...shared.styles.map((n) => ({ name: n, body: () => text(shared.cssDir, n) })),
        ];
        for (const s of list) {
          ctx.write(path.join(rel, css, s.name), s.body());
          written.css.push(posixJoin(css, s.name));
        }
      }
      if (fonts) {
        for (const name of present) {
          ctx.copyFile(path.join(root, 'design', 'fonts', name), path.join(rel, fonts, name));
          written.fonts.push(posixJoin(fonts, name));
        }
      }
      return written;
    },

    /**
     * The synced engine into dist/<rel>, byte for byte (vendor/pixelclock/ is checked against SYNC.json first).
     * Pages (default): flat engine.js, schedule.js, [screens.js with screens: true], themes/*.js.
     * render: true (the still): simulator/... next to tools/render.js (screens.js included: render.js loads it).
     * Returns { files: [paths relative to dist/<rel>], scripts: [the page script order, flat layout only] }.
     */
    copyVendor(rel, { screens = false, render = false } = {}) {
      if (typeof rel !== 'string' || rel.trim() === '') throw new Error('ctx.copyVendor: rel (the folder under dist/) is required');
      const v = assertVendor(vendorPath);
      const files = [];
      for (const f of v.files) {
        const target = vendorTarget(f.path, { render, screens: screens || render });
        if (!target) continue;
        const p = file('copyVendor', path.join(rel, ...target.split('/')));
        const n = fsx.copyFile(path.join(vendorPath, ...f.path.split('/')), p);
        count(n);
        files.push(target);
      }
      log(`copy vendor/pixelclock/ -> ${distRel(out(rel))}/ (${files.length} files, ${render ? 'render layout' : 'page layout'}, bytes unchanged)`);
      const scripts = render ? [] : ['engine.js', 'schedule.js', ...vendorOrder().map((t) => t.file)].filter((s) => files.includes(s));
      return { files: files.sort(), scripts };
    },

    /**
     * The page script order, as paths relative to the piece folder:
     * <vendor>/engine.js, <js>/pcd-hook.js, <vendor>/schedule.js, <vendor>/themes/*.js (seasons, then holidays),
     * the generated <js>/pcd-tokens.js and <js>/pcd-anchors.js, then the src/shared scripts in documented order.
     * Only files that exist (or are generated) are listed; screens.js is never loaded by pages.
     */
    pageScripts({ js = 'js', vendor = 'js/pixelclock' } = {}) {
      return [
        posixJoin(vendor, 'engine.js'),
        ...(shared.hook ? [posixJoin(js, HOOK_SCRIPT)] : []),
        posixJoin(vendor, 'schedule.js'),
        ...vendorOrder().map((t) => posixJoin(vendor, t.file)),
        ...GENERATED_SCRIPTS.filter((n) => generated[n] !== undefined).map((n) => posixJoin(js, n)),
        ...shared.scripts.map((n) => posixJoin(js, n)),
      ];
    },
  };
  return ctx;
}

/** Check the inputs: config/user.json and vendor/pixelclock/. Returns { config, vendor, problems }. */
export function loadInputs(root) {
  const { config, problems } = loadConfig(root);
  let vendor = null;
  try {
    vendor = assertVendor(vendorDir(root));
  } catch (e) {
    problems.push(e.message);
  }
  return { config, vendor, problems };
}

function fmtBytes(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(2)} MB`;
}

/**
 * The engine refresh before a build. With a PixelClock checkout next to `root` (or PCD_PIXELCLOCK set) it runs
 * tools/sync.mjs into <root>/vendor/pixelclock/; with no checkout there it skips, and the build uses
 * vendor/pixelclock/ as it is. A PCD_PIXELCLOCK that names a missing folder still fails (the sync says why).
 * `run` stands in for the sync (tests). Resolves { code, status }.
 */
export async function defaultSync({ log = console.log, env = process.env, root = ROOT, run } = {}) {
  const S = await import('./sync.mjs');
  const source = S.defaultSource(env, root);
  if (!env[S.SOURCE_ENV] && !fs.existsSync(path.join(source, 'simulator', 'engine.js'))) {
    log('no PixelClock checkout next to this folder: building from vendor/pixelclock/ as it is');
    return { code: 0, status: 'skipped' };
  }
  return (run || S.runSync)({ log, source, vendorDir: path.join(path.resolve(root), 'vendor', 'pixelclock') });
}

/**
 * Run the build. Returns the exit code (0 ok, 1 error). Options make it testable:
 * { argv, root, dist, log, logError, sync: async ({ log, root }) => ({ code }) }.
 */
export async function main({ argv = process.argv.slice(2), root = ROOT, dist, log = console.log, logError = console.error, sync = defaultSync } = {}) {
  const args = parseArgs(argv);
  if (args.help) { log(USAGE); return 0; }
  if (args.errors.length) {
    logError(`[build] ${args.errors.join('; ')}\n${USAGE}`);
    return 1;
  }
  root = path.resolve(root);
  const distDir = path.resolve(dist || path.join(root, 'dist'));
  const started = Date.now();
  log(`[build] root ${root}${args.sync ? '' : ' (--no-sync)'}${args.render ? '' : ' (--no-render)'}`);

  if (args.sync) {
    const r = await sync({ log: (m) => log(`[sync] ${m}`), root });
    if (!r || r.code !== 0) {
      logError('[build] FAILED: the engine sync failed (vendor/pixelclock/ keeps its last good copy; rerun with --no-sync to build from it)');
      return 1;
    }
  }

  const { config, vendor, problems } = loadInputs(root);
  if (problems.length) {
    logError(`[build] FAILED before any piece ran:\n  - ${problems.join('\n  - ')}`);
    return 1;
  }
  log(`[build] config/user.json OK (units ${config.units}, clock ${config.clock}, ${config.shortcuts.length} shortcuts)`);
  log(`[build] vendor/pixelclock OK: ${vendor.files.length} files, clock commit ${String(vendor.sync.commit).slice(0, 7)}, synced ${vendor.sync.syncedAt}`);

  let gen;
  try {
    gen = await generateStage({ root, config, vendor: vendorDir(root) });
  } catch (e) {
    logError(`[build] FAILED in the generate stage: ${e && e.stack ? e.stack : e}`);
    return 1;
  }
  for (const n of gen.notes) log(`[build] ${n}`);

  const shared = sharedLists(root);
  if (shared.conflicts.length) {
    logError(`[build] FAILED: src/shared/ must not contain ${shared.conflicts.join(', ')} (generated by the build)`);
    return 1;
  }

  const selected = args.pieces.length ? PIECES.filter((p) => args.pieces.includes(p)) : PIECES;
  const results = [];
  for (const piece of selected) {
    const file = path.join(root, 'tools', 'build', `${piece}.mjs`);
    if (!fs.existsSync(file)) {
      log(`skip ${piece}: no plugin`);
      results.push({ piece, status: 'skipped', note: 'no plugin' });
      continue;
    }
    const t0 = Date.now();
    const ctx = createContext({ root, dist: distDir, config, tokens: gen.tokens, anchors: gen.anchors, generated: gen.generated, render: args.render, piece, log, shared });
    log(`[build] ${piece}: start`);
    try {
      const mod = await import(pathToFileURL(file).href);
      if (typeof mod.build !== 'function') throw new Error(`tools/build/${piece}.mjs does not export async function build(ctx)`);
      if (mod.piece !== undefined && mod.piece !== piece) throw new Error(`tools/build/${piece}.mjs exports piece = ${JSON.stringify(mod.piece)}, expected "${piece}"`);
      await mod.build(ctx);
      results.push({ piece, status: 'ok', ms: Date.now() - t0, files: ctx.stats.files, bytes: ctx.stats.bytes });
    } catch (e) {
      logError(`[${piece}] ERROR: ${e && e.stack ? e.stack : e}`);
      results.push({ piece, status: 'ERROR', ms: Date.now() - t0, files: ctx.stats.files, bytes: ctx.stats.bytes, note: String(e && e.message ? e.message : e).split('\n')[0] });
    }
  }

  // Zip the Lively package when the wallpaper piece built in this run.
  const wp = results.find((r) => r.piece === 'wallpaper');
  const wpDir = path.join(distDir, 'wallpaper');
  if (wp && wp.status === 'ok') {
    if (fsx.listFiles(wpDir).length) {
      try {
        fsx.zipDir(wpDir, path.join(distDir, ZIP_NAME));
        log(`[build] zip dist/wallpaper/ -> dist/${ZIP_NAME} (${fmtBytes(fs.statSync(path.join(distDir, ZIP_NAME)).size)})`);
      } catch (e) {
        logError(`[build] ERROR zipping dist/wallpaper: ${e.message}`);
        results.push({ piece: 'zip', status: 'ERROR', note: e.message.split('\n')[0] });
      }
    } else {
      log('[build] zip: dist/wallpaper/ is empty, nothing to zip');
    }
  }

  const errors = results.filter((r) => r.status === 'ERROR');
  const built = results.filter((r) => r.status === 'ok');
  log('');
  log('build summary');
  log(`  ${'piece'.padEnd(11)} ${'result'.padEnd(8)} ${'files'.padStart(5)}  ${'size'.padStart(9)}  ${'time'.padStart(7)}  note`);
  for (const r of results) {
    const files = r.files === undefined ? '-' : String(r.files);
    const size = r.bytes === undefined ? '-' : fmtBytes(r.bytes);
    const time = r.ms === undefined ? '-' : `${(r.ms / 1000).toFixed(1)} s`;
    log(`  ${r.piece.padEnd(11)} ${r.status.padEnd(8)} ${files.padStart(5)}  ${size.padStart(9)}  ${time.padStart(7)}  ${r.note || ''}`.trimEnd());
  }
  const secs = ((Date.now() - started) / 1000).toFixed(1);
  if (errors.length) {
    logError(`build FAILED: ${errors.length} step(s) with errors (${errors.map((r) => r.piece).join(', ')}); ${built.length} built, ${secs} s`);
    return 1;
  }
  log(`build OK: ${built.length} built, ${results.length - built.length} skipped, ${secs} s`);
  return 0;
}

function isMainModule() {
  if (typeof import.meta.main === 'boolean') return import.meta.main;
  if (!process.argv[1]) return false;
  try {
    return path.relative(fs.realpathSync(process.argv[1]), fileURLToPath(import.meta.url)) === '';
  } catch {
    return false;
  }
}

if (isMainModule()) {
  main().then(
    (code) => {
      process.exitCode = code;
      // A plugin that leaks a handle (server, browser) must not keep the build alive.
      setTimeout(() => process.exit(code), 3000).unref();
    },
    (e) => {
      console.error(e);
      process.exit(1);
    },
  );
}
